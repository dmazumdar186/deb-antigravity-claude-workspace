"""GreenJobs redirects: Cloudflare Bulk Redirects list + Worker fallback table + M2 coverage report.

description: Turns redirect_map.json (old Strategies URLs, both boards) into
  (a) a Cloudflare Bulk Redirects list (one JSON, both boards + the 8 sector
  domains -> /sectors/<slug>/ on greenjobs.co.uk), and (b) a small Worker
  table for what bulk redirects cannot express (old ASP query-string URLs,
  case / trailing-slash variants, job ids that are no longer live). Every
  /browse-jobs/{slug}/ facet is mapped to a filter URL on /jobs/ with
  build_site.py's own vocabulary (sector keywords, region aliases, contract
  types, employer names). Every target is checked against the site's route set
  (common.Routes); an unserved target aborts the build (exit 2). Offline by
  default; `crawl --live` does read-only GETs to measure M2 for real.
inputs: build [--map PATH] [--live-ids JSON] [--routes JSON] [--out DIR]
        crawl --live [--out DIR] [--limit N]   (network, read-only)
  --live-ids: {"ie": [...ids], "uk": [...]} or a D1 export ({"tables": {"jobs": rows}});
    default = the job ids redirect_map.json marks mapped (Sept snapshot; re-run with a D1 export before loading).
  --routes: {"ie": [paths], "uk": [paths]} published by the site build; replaces the build_site-derived static set.
outputs: <out>/bulk_redirects.json, <out>/worker_redirects.json, <out>/redirect_coverage.json (default ops/generated/);
  crawl: .tmp/greenjobs_ops/redirect_crawl.json (input to metrics.py M2). stdout: coverage summary.
"""

from __future__ import annotations

import argparse
import functools
import re
import sys
import urllib.parse
from collections import Counter
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common as C  # noqa: E402
from common import build_site as B  # noqa: E402

LIST_NAME = "greenjobs_legacy_redirects"
# Cloudflare free plan Bulk Redirects allowance (verify on the account's dashboard before loading).
FREE_TIER_MAX_ITEMS = 10_000
LIST_DESCRIPTION = "GreenJobs: old Strategies URLs and sector domains (generated by ops/redirects.py; load after zones are in Cloudflare)"


# ---------------------------------------------------------------- facet -> filter


def _text(slug: str) -> str:
    return re.sub(r"[-_]+", " ", slug.lower()).strip()


@functools.lru_cache(maxsize=None)
def sector_for(slug: str) -> str | None:
    """Canonical sector for a facet slug, via build_site.assign_sectors on the slug as a title.
    None when no taxonomy keyword is in the slug (assign_sectors would otherwise return its default).
    """
    text = _text(slug)
    if not any(B._title_hit(name, text) for name, *_ in B.TAXONOMY):
        return None
    return B.assign_sectors({"title": text})[0]


@functools.lru_cache(maxsize=None)
def _region_words(ed: str) -> tuple[dict[str, Any], tuple[str, ...]]:
    table = C.region_table(ed)
    words = {w.lower() for name, aliases in table["regions"].items() for w in [name, *aliases]}
    return table, tuple(sorted(words))


@functools.lru_cache(maxsize=None)
def region_for(slug: str, ed: str) -> str | None:
    table, words = _region_words(ed)
    text = _text(slug)
    if not any(w in text for w in words):  # cheap pre-filter; resolve_regions (build_site's own rule) decides
        return None
    got = B.resolve_regions({"region": text}, table, B.EDITIONS[ed])
    return got[0] if got and got[0] in table["regions"] else None


def type_for(slug: str) -> str | None:
    tags = B.contract_of({"type": _text(slug)})
    return tags[0] if tags else None


def facet_target(
    slug: str, facet_kind: str, ed: str, employers: set[str]
) -> tuple[str, str]:
    """(target path, match class) for one /browse-jobs/{slug}/ page."""
    s = slug.strip("/").lower()
    if facet_kind == "employer":
        if B.slugify(s) in employers:
            return f"/jobs/?employer={B.slugify(s)}", "filter:employer"
        return "/employers/", "fallback:employers"
    if facet_kind in ("region", "location"):
        r = region_for(s, ed)
        if r:
            return f"/jobs/?region={B.slugify(r)}", "filter:region"
    if facet_kind == "job_type":
        t = type_for(s)
        if t:
            return f"/jobs/?type={t}", "filter:type"
    sec = sector_for(s)
    if sec:
        return f"/jobs/?sector={C.sector_slug(sec)}", "filter:sector"
    if facet_kind not in ("region", "location"):
        r = region_for(s, ed)  # a "category" that is really a place
        if r:
            return f"/jobs/?region={B.slugify(r)}", "filter:region"
    return "/jobs/", "fallback:board"


# ---------------------------------------------------------------- inputs


def load_live_ids(
    path: Path | None, rmap: dict[str, Any]
) -> tuple[dict[str, set[str]], str]:
    if path:
        js = C.read_json(path)
        if isinstance(js, dict) and "tables" in js:
            out: dict[str, set[str]] = {"ie": set(), "uk": set()}
            for row in js["tables"].get("jobs", []):
                if row.get("status") == "live" and row.get("site") in out:
                    out[row["site"]].add(str(row.get("source_id") or row["id"]))
            return out, f"D1 export {path.name}"
        return {
            k: {str(i) for i in js.get(k, [])} for k in ("ie", "uk")
        }, f"id list {path.name}"
    out = {"ie": set(), "uk": set()}
    for ed, site in rmap["sites"].items():
        for e in site["entries"]:
            m = re.fullmatch(rf"/{ed}/jobs/([A-Za-z0-9_-]+)/", e.get("target") or "")
            if e["kind"] == "job" and m:
                out[ed].add(m.group(1))
    return (
        out,
        "ASSUMED: job ids redirect_map.json marks mapped (2026-09 snapshot), not a live list",
    )


def strip_edition(target: str, ed: str) -> str:
    return target[len(ed) + 1 :] if target.startswith(f"/{ed}/") else target


# ---------------------------------------------------------------- build


def plan(
    rmap: dict[str, Any],
    live_ids: dict[str, set[str]],
    static: dict[str, set[str]] | None = None,
    employers: dict[str, list[str]] | None = None,
) -> dict[str, Any]:
    """Pure: every old URL -> {old, target, class, via}; plus the route objects used to check targets."""
    routes = {
        ed: C.Routes(
            ed,
            live_ids.get(ed, set()),
            (static or {}).get(ed),
            (employers or {}).get(ed),
        )
        for ed in C.BOARDS
    }
    rows: list[dict[str, Any]] = []
    for ed, site in rmap["sites"].items():
        emp = routes[ed].vocab["employer"]
        for e in site["entries"]:
            old, kind = e["old"], e["kind"]
            prior = (
                strip_edition(e.get("target") or "", ed)
                if e.get("status") == "mapped"
                else ""
            )
            if kind == "job":
                m = re.match(r"^/jobs/([A-Za-z0-9_-]+)/", old) or re.search(
                    r"[?&]v=([A-Za-z0-9_-]+)", old
                )
                jid = m.group(1) if m else ""
                target, cls = (
                    (f"/jobs/{jid}/", "exact:job")
                    if jid in routes[ed].live_ids
                    else ("/jobs/", "fallback:board")
                )
            elif kind == "facet":
                slug = old.split("/browse-jobs/", 1)[1]
                if prior and routes[ed].serves(prior):
                    target, cls = prior, "exact:landing"
                else:
                    target, cls = facet_target(
                        slug, e.get("facet_kind") or "unknown", ed, emp
                    )
            elif prior and routes[ed].serves(prior):
                target, cls = prior, "exact:page"
            else:
                target, cls = "/", "fallback:home"
            via = "worker" if "?" in old else "bulk"
            rows.append(
                {
                    "site": ed,
                    "old": old,
                    "kind": kind,
                    "facet_kind": e.get("facet_kind"),
                    "target": target,
                    "class": cls,
                    "via": via,
                    "served": routes[ed].serves(target),
                }
            )
    return {"rows": rows, "routes": routes}


def bulk_item(source: str, target: str, subpath: bool = False) -> dict[str, Any]:
    return {
        "redirect": {
            "source_url": source,
            "target_url": target,
            "status_code": 301,
            "include_subdomains": True,
            "subpath_matching": subpath,
            "preserve_query_string": False,
            "preserve_path_suffix": False,
        }
    }


def bulk_list(rows: list[dict[str, Any]]) -> dict[str, Any]:
    items: dict[str, dict[str, Any]] = {}
    for r in rows:
        if r["via"] != "bulk":
            continue
        host = C.BOARDS[r["site"]]
        tgt = C.CANONICAL[r["site"]] + r["target"]
        for path in dict.fromkeys(
            [r["old"], r["old"].lower()]
        ):  # recorded spelling + lowercase (Worker normalises to it)
            src = host + path
            items.setdefault(src, bulk_item(src, tgt))
    for dom in C.SECTOR_DOMAINS:
        src = dom + "/"
        items[src] = bulk_item(
            src, C.CANONICAL["uk"] + C.sector_forward_path(dom), subpath=True
        )
    ordered = [items[k] for k in sorted(items)]
    if len(ordered) > FREE_TIER_MAX_ITEMS:
        raise SystemExit(
            f"FAIL  {len(ordered)} bulk items exceed the free-tier ceiling {FREE_TIER_MAX_ITEMS}"
        )
    return {
        "name": LIST_NAME,
        "kind": "redirect",
        "description": LIST_DESCRIPTION,
        "rule_expression": f"http.request.full_uri in ${LIST_NAME}",
        "items": ordered,
    }


def worker_table(routes: dict[str, C.Routes]) -> dict[str, Any]:
    hosts = {}
    for ed, apex in C.BOARDS.items():
        hosts[apex] = ed
        hosts["www." + apex] = ed
    return {
        "version": 1,
        "hosts": hosts,
        "canonical": C.CANONICAL,
        "live_ids": {ed: sorted(r.live_ids) for ed, r in routes.items()},
        "regions": {ed: C.region_slugs(ed) for ed in C.BOARDS},
        "rules": [
            "jobresults.asp?lstRegion|lstVicinity=<r> -> /jobs/?region=<slug> when <r> is a region or alias, else /jobs/",
            "jobresults.asp (any other query) -> /jobs/",
            "jobview.asp?v=<id> and /jobs/<id>/<slug>.asp -> /jobs/<id>/ when live, else /jobs/",
            "/browse-jobs/<slug> in another case or without the slash -> lowercase + slash (bulk list holds that form)",
            "/browse-jobs/<slug>/ already canonical (bulk missed) -> /jobs/",
            "any other *.asp -> /",
        ],
    }


def coverage(rows: list[dict[str, Any]]) -> dict[str, Any]:
    total = len(rows)
    served = sum(r["served"] for r in rows)
    specific = sum(not r["class"].startswith("fallback") for r in rows)
    by_class = Counter(r["class"] for r in rows)
    facets = [r for r in rows if r["kind"] == "facet"]
    leftovers = sorted(
        {
            (r["site"], r["old"], r["facet_kind"] or r["kind"], r["target"])
            for r in rows
            if r["class"].startswith("fallback")
        }
    )
    return {
        "metric": "M2 (static pre-check; the graded M2 is the live crawl)",
        "old_urls": total,
        "targets_served": served,
        "served_pct": round(100 * served / total, 2) if total else None,
        "specific_match_pct": round(100 * specific / total, 2) if total else None,
        "facets": len(facets),
        "facets_specific": sum(not r["class"].startswith("fallback") for r in facets),
        "by_class": dict(sorted(by_class.items())),
        "unserved": [r for r in rows if not r["served"]],
        "leftovers": [
            {"site": s, "old": o, "kind": k, "target": t} for s, o, k, t in leftovers
        ],
    }


def build(
    map_path: Path, live_ids_path: Path | None, routes_path: Path | None, out: Path
) -> dict[str, Any]:
    rmap = C.read_json(map_path)
    live, live_src = load_live_ids(live_ids_path, rmap)
    static = None
    if routes_path:
        js = C.read_json(routes_path)
        static = {ed: set(js.get(ed, [])) for ed in C.BOARDS}
    p = plan(rmap, live, static)
    cov = coverage(p["rows"])
    cov["live_ids_source"] = live_src
    cov["route_set_source"] = (
        f"published routes {routes_path.name}"
        if routes_path
        else "build_site.py vocabulary (PAGES_FOR_SITEMAP, LANDINGS, TAXONOMY, regions, CONTRACT_LABEL, clients)"
    )
    if cov["unserved"]:
        C.write_json(out / "redirect_coverage.json", cov)
        raise SystemExit(
            f"FAIL  {len(cov['unserved'])} redirect targets are not served by the new site (see redirect_coverage.json)"
        )
    bl = bulk_list(p["rows"])
    wt = worker_table(p["routes"])
    for name, data in (
        ("bulk_redirects.json", bl),
        ("worker_redirects.json", wt),
        ("redirect_coverage.json", cov),
    ):
        if (
            C.read_json(out / name) != data
        ):  # idempotent: unchanged inputs rewrite nothing
            C.write_json(out / name, data)
    cov["bulk_items"] = len(bl["items"])
    return cov


# ---------------------------------------------------------------- live crawl (M2, read-only)


def crawl(rows: list[dict[str, Any]], fetch_head, max_hops: int = 2) -> dict[str, Any]:
    """fetch_head(url) -> (status, location|None). An old URL passes when it ends on 200 within max_hops redirects."""
    ok, fails = 0, []
    for r in rows:
        url = f"https://{C.BOARDS[r['site']]}{r['old']}"
        status, hops = None, 0
        for _ in range(max_hops + 1):
            try:
                status, loc = fetch_head(url)
            except (
                Exception
            ) as e:  # network error counts as a failed URL, recorded with its type
                status, loc = f"error:{type(e).__name__}", None
                break
            if status in (301, 302, 307, 308) and loc:
                hops += 1
                url = urllib.parse.urljoin(url, loc)
                continue
            break
        if status == 200 and hops <= max_hops:
            ok += 1
        else:
            fails.append(
                {
                    "old": r["old"],
                    "site": r["site"],
                    "status": status,
                    "hops": hops,
                    "last": url,
                }
            )
    return {
        "checked": len(rows),
        "ok_le_2_hops": ok,
        "failures": fails[:200],
        "at": C.now_iso(),
    }


def _live_head(url: str) -> tuple[int, str | None]:
    import urllib.request

    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *a, **k):
            return None

    opener = urllib.request.build_opener(NoRedirect)
    req = urllib.request.Request(
        url, method="GET", headers={"User-Agent": "GreenJobsOps/1.0"}
    )
    try:
        with opener.open(req, timeout=10) as resp:
            return resp.status, resp.headers.get("Location")
    except urllib.error.HTTPError as e:
        return e.code, e.headers.get("Location")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--map", type=Path, default=C.REDIRECT_MAP)
    b.add_argument("--live-ids", type=Path)
    b.add_argument("--routes", type=Path)
    b.add_argument("--out", type=Path, default=C.GENERATED)
    c = sub.add_parser("crawl")
    c.add_argument(
        "--live",
        action="store_true",
        help="required: makes read-only GET requests to the production hosts",
    )
    c.add_argument("--map", type=Path, default=C.REDIRECT_MAP)
    c.add_argument("--out", type=Path, default=C.STATE_DIR / "redirect_crawl.json")
    c.add_argument("--limit", type=int, default=0)
    a = ap.parse_args(argv)
    if a.cmd == "build":
        cov = build(a.map, a.live_ids, a.routes, a.out)
        print(
            f"ok: {cov['old_urls']} old URLs, {cov['served_pct']}% land on a served page, "
            f"{cov['specific_match_pct']}% on a specific page/filter, {len(cov['leftovers'])} fall back to board/home/employers; "
            f"{cov['bulk_items']} bulk items; live ids: {cov['live_ids_source']}"
        )
        return 0
    if not a.live:
        print(
            "crawl makes network requests; pass --live (read-only GETs, no auth). Nothing done."
        )
        return 0
    rows = plan(C.read_json(a.map), {"ie": set(), "uk": set()})["rows"]
    rows = rows[: a.limit] if a.limit else rows
    res = crawl(rows, _live_head)
    C.write_json(a.out, res)
    print(
        f"crawl: {res['ok_le_2_hops']}/{res['checked']} end on 200 in <=2 hops -> {a.out}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
