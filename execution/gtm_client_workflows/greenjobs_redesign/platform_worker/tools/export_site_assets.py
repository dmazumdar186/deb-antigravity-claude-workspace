"""Export the static redesign's page shell, templates and maps into the platform Worker.

description: The Worker renders job pages from D1 with the SAME templates and
  shell as build_site.py. It cannot read src/templates at runtime, so this
  script freezes them into src/site_assets.gen.js (templates _shell, job, jobs,
  _fit; the two edition maps; per-site shell data: contact, network sites,
  social links, B Corp / 1% badge sizes; quick-match examples). --check exits 1
  when the committed file is stale, so a template edit cannot silently drift
  from the Worker (run_tests.sh runs --check).
inputs: --src <redesign src dir> (default: deliverables/greenjobs_redesign_2026-09-22/src),
  --check (compare only, write nothing)
outputs: execution/gtm_client_workflows/greenjobs_redesign/platform_worker/src/site_assets.gen.js
  (or exit 1 + a one-line reason with --check)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKER = HERE.parent
REPO = WORKER.parents[3]
sys.path.insert(0, str(WORKER.parent))
import build_site  # noqa: E402

OUT = WORKER / "src" / "site_assets.gen.js"
TEMPLATES = ("_shell", "job", "jobs", "_fit")


def payload(src: Path) -> dict:
    brief = build_site.read_brief(src)
    logos = src / "assets" / "logos"
    for key, name in (
        ("bcorp_size", "b-corp-logo.svg"),
        ("onepct_size", "1fortheplanet.svg"),
    ):
        if (logos / name).is_file():
            brief[key] = list(build_site.image_size(logos / name))
    shell = {}
    for ed in ("ie", "uk"):
        raw = json.loads((src / "data" / f"{ed}.json").read_text(encoding="utf-8"))
        shell[ed] = {
            "site": str(raw.get("site") or build_site.EDITIONS[ed]["domain"]),
            "contact": {
                "phones": (raw.get("contact") or {}).get("phones") or [],
                "emails": (raw.get("contact") or {}).get("emails") or [],
            },
            "network_sites": [
                {"url": s.get("url", ""), "name": s.get("name", "")}
                for s in raw.get("network_sites") or []
            ],
            "social": build_site.social_links(src, ed),
            "fit_examples": build_site.FIT_EXAMPLES[ed],
            "fit_placeholder": build_site.FIT_PLACEHOLDER[ed],
        }
    return {
        "templates": {
            t: (src / "templates" / f"{t}.html").read_text(encoding="utf-8")
            for t in TEMPLATES
        },
        "maps": {
            ed: (src / "assets" / "maps" / f"{ed}.svg")
            .read_text(encoding="utf-8")
            .strip()
            for ed in ("ie", "uk")
        },
        "shell": shell,
        "analytics": analytics(src),
        "brief": {
            "b_corp": bool(brief.get("b_corp")),
            "bcorp_size": brief.get("bcorp_size"),
            "onepct_size": brief.get("onepct_size"),
        },
    }


def analytics(src: Path) -> dict:
    """GA4 ids + production hosts (src/analytics.json): the Worker emits the tag only on a production host."""
    f = src / "analytics.json"
    cfg = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}
    hosts = cfg.get("production_hosts") or {}
    out = {}
    for ed, e in (cfg.get("editions") or {}).items():
        if build_site.GA_ID_RE.match(str(e.get("ga4", ""))):
            out[ed] = {"ga4": e["ga4"], "gsc_token": "".join(c for c in str(e.get("gsc_token") or "") if c.isalnum() or c in "_-"),
                       "hosts": list(hosts.get(ed, []))}
    return out


def render_module(p: dict) -> str:
    head = "// GENERATED by tools/export_site_assets.py from the redesign src/ (templates, maps, shell data). Do not edit.\n"
    return head + "".join(
        f"export const {k.upper()} = {json.dumps(v, ensure_ascii=False, indent=None, sort_keys=True)};\n"
        for k, v in p.items()
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--src",
        type=Path,
        default=REPO / "deliverables" / "greenjobs_redesign_2026-09-22" / "src",
    )
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render_module(payload(a.src))
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"FAIL  {OUT.name} is stale: run python3 {Path(__file__).relative_to(REPO)}"
            )
            return 1
        print(f"ok: {OUT.name} matches the redesign templates")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
